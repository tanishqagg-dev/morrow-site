import { chromium } from "playwright-core";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";

const browser = await chromium.launch({ headless: true });
const dir = new URL("../qa/morrow-motion/", import.meta.url).pathname;
await mkdir(dir, { recursive: true });
const errors = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
page.on("pageerror", error => errors.push(error.message));
try {
  await page.goto("http://127.0.0.1:8796", { waitUntil: "networkidle" });
  await page.waitForTimeout(1300);
  assert.equal(await page.locator("html.lenis").count(), 1, "Smooth scroll starts");
  assert.equal(await page.locator(".pin-spacer").count(), 1, "Desktop story is scroll-driven");
  const start = await page.locator("[data-scroll-story]").evaluate(node => node.getBoundingClientRect().top + scrollY);
  await page.evaluate(y => window.scrollTo(0, y), start + 20);
  await page.waitForTimeout(1000);
  await page.screenshot({ path: dir + "story-context.png" });
  assert.ok(await page.locator("[data-story-result]").evaluate(node => Number(getComputedStyle(node).opacity)) < .1);
  await page.evaluate(y => window.scrollTo(0, y), start + 980);
  await page.waitForTimeout(1100);
  assert.ok(await page.locator("[data-story-result]").evaluate(node => Number(getComputedStyle(node).opacity)) > .95, "Scroll resolves files into a reviewable result");
  await page.screenshot({ path: dir + "story-result.png" });
  await page.getByRole("button", { name: "Pause animations", exact: true }).click();
  assert.equal(await page.locator("html.lenis").count(), 0, "Pause destroys smooth scrolling");
  assert.equal(await page.locator(".pin-spacer").count(), 0, "Pause restores natural layout");
  await page.locator("[data-scroll-story]").scrollIntoViewIfNeeded();
  await page.screenshot({ path: dir + "story-paused.png" });
  await page.getByRole("button", { name: "Resume animations", exact: true }).click();
  assert.equal(await page.locator(".pin-spacer").count(), 1);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.waitForTimeout(1500);
  await page.getByRole("link", { name: "Book a personal demo" }).first().click();
  await page.waitForTimeout(2000);
  assert.ok(await page.locator('form[name="morrow-demo"]').evaluate(node => { const box = node.getBoundingClientRect(); return box.top >= 0 && box.bottom <= innerHeight; }), "CTA brings the complete form into view after pinned story");
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.waitForFunction(() => !document.documentElement.classList.contains("lenis"));
  assert.equal(await page.locator("html.lenis").count(), 0);
  assert.equal(await page.locator(".pin-spacer").count(), 0);
  assert.equal(await page.locator("[data-story-result]").evaluate(node => getComputedStyle(node).visibility), "visible");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.waitForFunction(() => document.documentElement.classList.contains("lenis"));
  await page.locator("[data-scroll-story]").scrollIntoViewIfNeeded();
  assert.equal(await page.locator(".pin-spacer").count(), 0, "Mobile has no pinned section");
  assert.ok(await page.locator("[data-story-mascot]").evaluate(node => { const box = node.getBoundingClientRect(); return Math.abs(box.left + box.width / 2 - innerWidth / 2) < 3; }), "Mascot stays centered after switching from desktop to mobile");
  await page.screenshot({ path: dir + "story-mobile.png" });
  const staticContext = await browser.newContext({ javaScriptEnabled: false, viewport: { width: 1440, height: 1000 } });
  const staticPage = await staticContext.newPage();
  await staticPage.goto("http://127.0.0.1:8796");
  assert.equal(await staticPage.getByRole("heading", { name: "Your week. A little clearer." }).isVisible(), true, "Result exists without JavaScript");
  assert.deepEqual(errors, []);
  console.log("PASS: actual scroll transforms, Lenis, pinning, pause/resume cleanup, anchor destination, live reduced-motion changes, mobile natural scrolling, no-JS content, no runtime exceptions.");
} finally { await browser.close(); }
